def sunburst(center, radius, n, col_a, col_b, name, rot_frames=None, y_axis=True):
    root = empty(name, loc=center, rot=(math.pi / 2, 0, 0) if y_axis else (0, 0, 0))
    root.rotation_mode = "ZXY"   # spin about the disc's own axis
    disc = cyl((0, 0, -0.02), r=radius, depth=0.02, m=emission_mat(name + "_a", col_a, 1.0), parent=root, verts=64)
    mb = emission_mat(name + "_b", col_b, 1.0)
    for i in range(n):
        a = i / n * math.tau
        mesh = bpy.data.meshes.new("ray")
        w = math.pi / n * 0.55
        verts = [(0, 0, 0), (math.cos(a - w) * radius, math.sin(a - w) * radius, 0), (math.cos(a + w) * radius, math.sin(a + w) * radius, 0)]
        mesh.from_pydata(verts, [], [(0, 1, 2)])
        o = bpy.data.objects.new("ray", mesh)
        link(o)
        o.data.materials.append(mb)
        o.parent = root
    if rot_frames:
        f0, f1 = rot_frames
        kf(root, f0, rotation_euler=(math.pi / 2, 0, 0), interp="LINEAR")
        kf(root, f1, rotation_euler=(math.pi / 2, 0, math.radians(60)))
    return root

