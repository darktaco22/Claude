_mats = {}
def mat(name, color, rough=0.45, metal=0.0, emit=0.0, emit_color=None):
    if name in _mats:
        return _mats[name]
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    b = m.node_tree.nodes["Principled BSDF"]
    b.inputs["Base Color"].default_value = hexc(color)
    b.inputs["Roughness"].default_value = rough
    b.inputs["Metallic"].default_value = metal
    if emit:
        b.inputs["Emission Color"].default_value = hexc(emit_color or color)
        b.inputs["Emission Strength"].default_value = emit
    _mats[name] = m
    return m

def emission_mat(name, color, strength=1.0):
    if name in _mats:
        return _mats[name]
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    nt = m.node_tree
    nt.nodes.clear()
    out = nt.nodes.new("ShaderNodeOutputMaterial")
    em = nt.nodes.new("ShaderNodeEmission")
    em.inputs["Color"].default_value = hexc(color)
    em.inputs["Strength"].default_value = strength
    nt.links.new(em.outputs[0], out.inputs[0])
    _mats[name] = m
    return m

def image_mat(name, path, strength=1.0, alpha=False):
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    nt = m.node_tree
    nt.nodes.clear()
    out = nt.nodes.new("ShaderNodeOutputMaterial")
    tex = nt.nodes.new("ShaderNodeTexImage")
    tex.image = bpy.data.images.load(path)
    tex.interpolation = "Cubic"
    em = nt.nodes.new("ShaderNodeEmission")
    em.inputs["Strength"].default_value = strength
    nt.links.new(tex.outputs["Color"], em.inputs["Color"])
    if alpha:
        tr = nt.nodes.new("ShaderNodeBsdfTransparent")
        mix = nt.nodes.new("ShaderNodeMixShader")
        nt.links.new(tex.outputs["Alpha"], mix.inputs[0])
        nt.links.new(tr.outputs[0], mix.inputs[1])
        nt.links.new(em.outputs[0], mix.inputs[2])
        nt.links.new(mix.outputs[0], out.inputs[0])
        m.blend_method = "HASHED"
    else:
        nt.links.new(em.outputs[0], out.inputs[0])
    return m, tex.image

def link(o):
    if o.name not in scene.collection.objects and not o.users_collection:
        scene.collection.objects.link(o)
    return o

def finish(o, m=None, smooth=False, bevel=0.0, parent=None):
    if m:
        o.data.materials.clear()
        o.data.materials.append(m)
    if smooth and o.type == "MESH":
        o.data.shade_smooth()
    if bevel:
        bv = o.modifiers.new("bevel", "BEVEL")
        bv.width = bevel
        bv.segments = 3
        bv.harden_normals = False
    if parent:
        o.parent = parent
    return o

def sphere(loc, r=1, scale=(1, 1, 1), m=None, parent=None, name="sphere", seg=32):
    bpy.ops.mesh.primitive_uv_sphere_add(segments=seg, ring_count=seg // 2, radius=r, location=loc)
    o = bpy.context.active_object
    o.name = name
    o.scale = scale
    return finish(o, m, smooth=True, parent=parent)

def cube(loc, size=(1, 1, 1), m=None, parent=None, bevel=0.0, name="cube", rot=(0, 0, 0)):
    bpy.ops.mesh.primitive_cube_add(size=1, location=loc, rotation=rot)
    o = bpy.context.active_object
    o.name = name
    o.scale = size
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    return finish(o, m, bevel=bevel, parent=parent)

def cyl(loc, r=1, depth=1, m=None, parent=None, verts=32, name="cyl", rot=(0, 0, 0), smooth=True, bevel=0.0):
    bpy.ops.mesh.primitive_cylinder_add(vertices=verts, radius=r, depth=depth, location=loc, rotation=rot)
    o = bpy.context.active_object
    o.name = name
    finish(o, m, bevel=bevel, parent=parent)
    if smooth:
        o.data.shade_smooth()
        o.data.set_sharp_from_angle(angle=math.radians(40))
    return o

def cone(loc, r1=1, r2=0, depth=1, m=None, parent=None, verts=32, name="cone", rot=(0, 0, 0)):
    bpy.ops.mesh.primitive_cone_add(vertices=verts, radius1=r1, radius2=r2, depth=depth, location=loc, rotation=rot)
    o = bpy.context.active_object
    o.name = name
    finish(o, m, smooth=True, parent=parent)
    o.data.set_sharp_from_angle(angle=math.radians(40))
    return o

def empty(name, loc=(0, 0, 0), parent=None, rot=(0, 0, 0)):
    o = bpy.data.objects.new(name, None)
    o.location = loc
    o.rotation_euler = rot
    link(o)
    if parent:
        o.parent = parent
    return o

def kf(o, f, interp=None, easing="AUTO", **props):
    for k, v in props.items():
        setattr(o, k, v)
        o.keyframe_insert(data_path=k, frame=f)
    if interp:
        for fc in o.animation_data.action.fcurves:
            if fc.data_path in props:
                for k in fc.keyframe_points:
                    if abs(k.co.x - f) < 0.01:
                        k.interpolation = interp
                        k.easing = easing

def text3d(body, size, color, name="txt", outline=PURPLE_D, extrude=0.05, emit=0.45, parent=None, loc=(0, 0, 0)):
    root = empty(name, loc=loc, parent=parent)
    def mk(offset, ext, m, z):
        cu = bpy.data.curves.new(name + "_c", "FONT")
        cu.body = body
        cu.font = FONT
        cu.size = size
        cu.align_x = "CENTER"
        cu.align_y = "CENTER"
        cu.extrude = ext
        cu.bevel_depth = size * 0.02
        cu.bevel_resolution = 2
        cu.offset = offset
        o = bpy.data.objects.new(name + "_o", cu)
        link(o)
        o.data.materials.append(m)
        o.parent = root
        o.location = (0, 0, z)
        return o
    mk(0, extrude, mat("txt_" + color, color, rough=0.3, emit=emit), 0)
    mk(size * 0.07, extrude + 0.02, mat("txt_out_" + outline, outline, rough=0.5), -0.04)
    return root

def pop(o, f_in, f_out=None, s=1.0, dur=9):
    """Scale-in with overshoot, scale-out (or vanish) later."""
    kf(o, f_in - 1, scale=(0, 0, 0), interp="CONSTANT")
    kf(o, f_in, scale=(0.001, 0.001, 0.001), interp="BACK", easing="EASE_OUT")
    kf(o, f_in + dur, scale=(s, s, s))
    if f_out:
        kf(o, f_out - 6, scale=(s, s, s), interp="BACK", easing="EASE_IN")
        kf(o, f_out, scale=(0, 0, 0))
    if f_in > 2:
        kf(o, 0, scale=(0, 0, 0), interp="CONSTANT")

def look_cam(name, loc, target, lens=35):
    cd = bpy.data.cameras.new(name)
    cd.lens = lens
    cd.clip_end = 400
    cam = bpy.data.objects.new(name, cd)
    link(cam)
    cam.location = loc
    tgt = empty(name + "_target", loc=target)
    c = cam.constraints.new("TRACK_TO")
    c.target = tgt
    c.track_axis = "TRACK_NEGATIVE_Z"
    c.up_axis = "UP_Y"
    return cam, tgt

