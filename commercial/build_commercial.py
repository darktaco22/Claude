        sphere((sx * 0.98, -0.15, 0.85), 0.27, (1, 1, 1.15), body_m, bob, name + "_arm")
        sphere((sx * 0.42, -0.2, 0.12), 0.3, (1, 1.3, 0.5), M_DARK if kind == "bull" else mat("paw", "#7A1E2C"), bob, name + "_foot")
