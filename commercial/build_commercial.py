def character(kind, name):
    """Chunky round mascot built from primitives. Faces -Y in local space."""
    root = empty(name)
    squash = empty(name + "_squash", parent=root)
    bob = empty(name + "_bob", parent=squash)
    if kind == "bull":
        body_m = mat("bull_body", "#2FC24F", rough=0.45)
        belly_m = mat("bull_belly", "#B8F5A8", rough=0.5)
        snout_m = mat("bull_snout", "#9BE58C", rough=0.4)
    else:
        body_m = mat("bear_body", "#D9344A", rough=0.5)
        belly_m = mat("bear_belly", "#FFC3B5", rough=0.5)
        snout_m = mat("bear_snout", "#F6B79E", rough=0.45)
    sphere((0, 0, 1.0), 1.0, (1.0, 0.92, 0.98), body_m, bob, name + "_body")
    sphere((0, -0.62, 0.72), 0.62, (1.0, 0.45, 0.85), belly_m, bob, name + "_belly")
    # eyes
    for sx in (-1, 1):
        sphere((sx * 0.34, -0.8, 1.3), 0.24, (1, 0.7, 1.1), M_WHITE, bob, name + "_eye")
        sphere((sx * 0.3, -0.98, 1.28), 0.11, (1, 0.6, 1.15), M_DARK, bob, name + "_pupil")
        sphere((sx * 0.27, -1.03, 1.34), 0.035, (1, 1, 1), emission_mat("glint", "#FFFFFF", 3), bob, name + "_glint", seg=12)
        # determined brows
        cube((sx * 0.36, -0.9, 1.6), (0.36, 0.1, 0.09), M_DARK, bob, bevel=0.03, rot=(0, sx * 0.35, 0), name=name + "_brow")
    # arms + feet
